function formsOf(c: string) {
  if (NON_CONNECTING.includes(c)) {
    return [
      { label: 'Отдельно', ar: c },
      { label: 'После буквы', ar: 'ـ' + c },
    ];
  }
  return [
    { label: 'Отдельно', ar: c },
    { label: 'В начале', ar: c + 'ـ' },
    { label: 'В середине', ar: 'ـ' + c + 'ـ' },
    { label: 'В конце', ar: 'ـ' + c },
  ];
}

