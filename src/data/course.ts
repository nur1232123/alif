const FATHA = 'َ';
const DAMMA = 'ُ';
const KASRA = 'ِ';
const DAMMATAN = 'ٌ';
const FATHATAN = 'ً';
const KASRATAN = 'ٍ';

/** Согласные для слогов: буква, русское чтение, латинская метка для id */
const C: [string, string, string][] = [
  ['ب', 'б', 'b'],
  ['ت', 'т', 't'],
  ['م', 'м', 'm'],
  ['ن', 'н', 'n'],
  ['ك', 'к', 'k'],
  ['ل', 'л', 'l'],
];

type Vowel = { mark: string; tail: string; sound: string; tag: string; note: string };

const SHORT: Vowel[] = [
  { mark: FATHA, tail: '', sound: 'а', tag: 'a', note: 'Фатха: чёрточка над буквой даёт «а»' },
  { mark: KASRA, tail: '', sound: 'и', tag: 'i', note: 'Кясра: чёрточка под буквой даёт «и»' },
  { mark: DAMMA, tail: '', sound: 'у', tag: 'u', note: 'Дамма: маленькая вау над буквой даёт «у»' },
];
const LONG: Vowel[] = [
  { mark: FATHA, tail: 'ا', sound: 'аа', tag: 'aa', note: 'Алиф после фатхи тянет звук' },
  { mark: KASRA, tail: 'ي', sound: 'ии', tag: 'ii', note: 'Йа после кясры тянет звук' },
  { mark: DAMMA, tail: 'و', sound: 'уу', tag: 'uu', note: 'Вау после даммы тянет звук' },
];
const TANWEEN: Vowel[] = [
  { mark: DAMMATAN, tail: '', sound: 'ун', tag: 'un', note: 'Две даммы: «ун»' },
  { mark: FATHATAN, tail: 'ا', sound: 'ан', tag: 'an', note: 'Две фатхи и алиф: «ан»' },
  { mark: KASRATAN, tail: '', sound: 'ин', tag: 'in', note: 'Две кясры: «ин»' },
];

const syllables = (consonants: string, vowels: Vowel[]): Item[] =>
  C.filter(([c]) => consonants.includes(c)).flatMap(([c, r, tag]) =>
    vowels.map((v) => ({
      id: `s-${tag}${v.tag}`,
      ar: c + v.mark + v.tail,
      say: c + v.mark + v.tail,
      ru: r + v.sound,
      family: c,
      note: c === 'ل' && v.tail === 'ا' ? 'Лям и алиф пишутся вместе, особым знаком' : v.note,
    })),
  );

const words = (week: number, rows: [string, string, string?][]): Item[] =>
  rows.map(([ar, ru, note], i) => ({ id: `w${week}-${i + 1}`, ar, say: ar, ru, note }));


